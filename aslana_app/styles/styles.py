from enum import Enum

class Color (Enum):
    # Fondo muy claro
    VERY_LIGHT = "#E3F0FA"
    # Turquesa claro (crestas de las olas)
    LIGHT = "#2BC4E8"
    # Azul oceánico medio (transición del texto y olas)
    PRIMARY = "#0077C2"
    # Azul profundo (color principal del texto)
    DARK = "#005A9E"
    # Verde azulado (profundidad de las olas)
    GREEN = "#009E8E"
    # Blanco
    WHITE = "#FFFFFF"
    # Negro
    BLACK = "#000000"

